import { createBrowserRouter, Navigate } from 'react-router-dom'
import { AppLayout } from '../components/AppLayout'
import { ProtectedRoute } from '../components/ProtectedRoute'
import { AuthPage } from '../pages/AuthPage'
import { AccountPage } from '../pages/AccountPage'
import { DashboardPage } from '../pages/DashboardPage'
import { CreateLobbyPage } from '../pages/CreateLobbyPage'
import { GameLobbyPage } from '../pages/GameLobbyPage'
import { JoinLobbyPage } from '../pages/JoinLobbyPage'
import { InviteJoinPage } from '../pages/InviteJoinPage'
export const router = createBrowserRouter([{ path: '/auth', element: <AuthPage /> }, { element: <ProtectedRoute />, children: [{ element: <AppLayout />, children: [{ path: '/', element: <DashboardPage /> }, { path: '/account', element: <AccountPage /> }, { path: '/lobby/create', element: <CreateLobbyPage /> }, { path: '/lobby/join', element: <JoinLobbyPage /> }, { path: '/join/:gameCode', element: <InviteJoinPage /> }, { path: '/games/:gameCode', element: <GameLobbyPage /> }] }] }, { path: '*', element: <Navigate to="/" replace /> }])
